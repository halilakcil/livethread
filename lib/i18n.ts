const dictionaries = { tr, en } as const;

export type TranslationKey = keyof typeof tr;

export function t(locale: AppLocale, key: TranslationKey): string {
  return dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
}

export function useI18n() {
  const locale = useSettings((s) => (s.locale === "en" ? "en" : "tr"));
  const contentLanguage = useSettings((s) => (s.contentLanguage === "en" ? "en" : "tr"));
  const setLocale = useSettings((s) => s.setLocale);
  const setContentLanguage = useSettings((s) => s.setContentLanguage);
  const translate = React.useCallback((key: TranslationKey): string => t(locale, key), [locale]);
  return {
    locale,
    contentLanguage,
    setLocale,
    setContentLanguage,
    t: translate,
  };
}

export function contentLanguageLabel(lang: ContentLanguage, ui: AppLocale): string {
  return lang === "en" ? t(ui, "english") : t(ui, "turkish");
}
